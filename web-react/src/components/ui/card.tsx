import { cn } from "@/lib/utils"

function Card({
  className,
  size = "default",
  variant = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm"; variant?: "default" | "dashed" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      data-variant={variant}
      className={cn(
        "group/card flex flex-col gap-(--card-spacing) overflow-hidden bg-card py-(--card-spacing) text-sm text-card-foreground ring-1 ring-foreground/10 [--card-spacing:--spacing(6)] has-[>img:first-child]:pt-0 data-[size=sm]:[--card-spacing:--spacing(4)]",
        variant === "dashed" &&
          "relative ring-0 before:pointer-events-none before:absolute before:inset-0 before:content-[''] before:[background-image:repeating-linear-gradient(to_bottom,var(--border)_0_5px,transparent_5px_7px),repeating-linear-gradient(to_right,var(--border)_0_5px,transparent_5px_7px),repeating-linear-gradient(to_bottom,var(--border)_0_5px,transparent_5px_7px),repeating-linear-gradient(to_right,var(--border)_0_5px,transparent_5px_7px)] before:[background-position:0_0,0_0,100%_0,0_100%] before:[background-repeat:repeat-y,repeat-x,repeat-y,repeat-x] before:[background-size:1px_7px,7px_1px,1px_7px,7px_1px] before:[background-origin:border-box] before:[background-clip:border-box]",
        className
      )}
      {...props}
    />
  )
}

